/** An irregular closed area around a centre; `r` is roughly the radius in km. */
function blob(lat: number, lng: number, r: number, wobble: number[]): Point[] {
  const dLat = r / 111;
  const dLng = r / (111 * Math.cos((lat * Math.PI) / 180));
  return wobble.map((w, i) => {
    const a = (i / wobble.length) * 2 * Math.PI;
    return [
      Number((lat + Math.sin(a) * dLat * w).toFixed(5)),
      Number((lng + Math.cos(a) * dLng * w).toFixed(5)),
    ];
  });
}

